/**
 * Generates src/css/sidebar-icons.css from Lucide's SVG sources.
 *
 *   node scripts/build-sidebar-icons.cjs
 *
 * Sidebar and navbar items cannot render a React component — Docusaurus only
 * gives us a `className`. So each icon is emitted as a CSS mask on a ::before
 * pseudo-element, painted with `background-color: currentColor`. That keeps the
 * icon on the same colour as its label in light, dark, hover and active states,
 * which an <img> or a plain background-image could not do.
 *
 * Where the className actually lands (verified against built output):
 *   navbar item      <a class="navbar__item navbar__link si-x">
 *   sidebar link     <li class="menu__list-item si-x"><a class="menu__link">
 *   sidebar category <li class="menu__list-item si-x">
 *                      <div class="menu__list-item-collapsible">
 *                        <a class="menu__link">
 *
 * The category case is why a bare `.si-x > .menu__link` selector does not
 * work — there is a collapsible wrapper in between. It also has to stay a
 * child combinator, not a descendant one, or every nested page inside the
 * category would inherit the parent's icon.
 *
 * Add a class to MAP below, then reference it as `className: "si-<name>"` in
 * sidebars.js or docusaurus.config.js.
 */
const fs = require("fs");
const path = require("path");

const ICON_DIR = path.join("node_modules", "lucide-static", "icons");

// css class suffix -> lucide icon file name
const MAP = {
  // top-level guide sections
  rocket: "rocket",
  layers: "layers",
  tenancy: "building-2",
  backend: "server",
  frontend: "code-xml",
  modules: "boxes",
  ops: "cloud-upload",
  api: "cable",
  ms1: "shield-check",
  book: "book-open",

  // module groups
  people: "users",
  time: "clock",
  payroll: "wallet",
  talent: "target",
  work: "list-checks",
  analytics: "chart-column",
  platform: "settings",

  // API groups
  identity: "key-round",
  peopleops: "user-round-cog",
  delivery: "ticket",
  compliance: "scale",
};

/**
 * Every place an icon class can sit, relative to the link it decorates.
 * `base` is a bare selector fragment such as `.si-rocket` or `[class*="si-"]`.
 */
const sel = (base, suffix = "") =>
  [
    `${base} > .menu__list-item-collapsible > .menu__link${suffix}`, // category
    `${base} > .menu__link${suffix}`, // sidebar leaf link
    `${base}.menu__link${suffix}`, // class on the link itself
    `${base}.navbar__link${suffix}`, // navbar item
  ].join(",\n");

const ANY = '[class*="si-"]';

const out = [];
out.push("/*");
out.push(" * GENERATED by scripts/build-sidebar-icons.cjs — do not edit by hand.");
out.push(" * Icons: Lucide (ISC), masked so they follow currentColor.");
out.push(" */");
out.push("");

// Infima already gives .menu__link `display:flex; flex:1; gap:.5rem`, so the
// ::before slots in as a flex item and the gap spaces it — overriding display
// there would collapse the link's full-width hover target. Navbar links are
// inline-block and do need converting.
out.push(`${ANY}.navbar__link {
  display: inline-flex;
  align-items: center;
  gap: 0.45em;
}`);
out.push("");

// `custom.css` also decorates `.menu__link::before` (a 3px category bar,
// absolutely positioned). That rule now excludes icon items, but the resets
// below keep the icon correct even if another ::before rule reappears —
// this pseudo-element is shared real estate.
out.push(`${sel(ANY, "::before")} {
  content: "";
  position: static;
  inset: auto;
  transform: none;
  width: 1em;
  height: 1em;
  flex: none;
  border-radius: 0;
  background: none;
  background-color: currentColor;
  -webkit-mask-repeat: no-repeat;
          mask-repeat: no-repeat;
  -webkit-mask-position: center;
          mask-position: center;
  -webkit-mask-size: contain;
          mask-size: contain;
  opacity: 0.85;
}`);
out.push("");

let n = 0;
for (const [cls, icon] of Object.entries(MAP)) {
  const file = path.join(ICON_DIR, `${icon}.svg`);
  if (!fs.existsSync(file)) {
    console.error(`  MISSING lucide icon: ${icon}.svg (for .si-${cls})`);
    process.exitCode = 1;
    continue;
  }
  // Lucide ships stroke="currentColor"; inside a mask only alpha matters, so
  // force an opaque stroke and flatten whitespace for the data URI.
  const svg = fs
    .readFileSync(file, "utf8")
    .replace(/stroke="currentColor"/, 'stroke="#000"')
    .replace(/\s*\n\s*/g, " ")
    .trim();
  const uri = `data:image/svg+xml,${encodeURIComponent(svg)}`;

  out.push(`${sel(`.si-${cls}`, "::before")} {
  -webkit-mask-image: url("${uri}");
          mask-image: url("${uri}");
}`);
  n++;
}

const dest = path.join("src", "css", "sidebar-icons.css");
fs.writeFileSync(dest, out.join("\n") + "\n");
console.log(`${dest} written — ${n} icons`);
